// Builds hooks/vendor/math-svg.js and its chunk: the TeX to SVG renderer of MathJax (Apache-2.0) bundled into ES
// modules the mod imports. The mod runs without Node, so it cannot import the package. Run after changing the version
// in package.json: `npm run build:math`.

import { build } from "esbuild";
import { Buffer } from "node:buffer";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const packageRoot = join(root, "node_modules", "mathjax-full");
const outDir = join(root, "hooks", "vendor");
const ALLOWED_LICENSES = new Set(["Apache-2.0", "MIT"]);
const CONFIGURATIONS = {
  base: "Base",
  ams: "Ams",
  newcommand: "Newcommand",
  boldsymbol: "Boldsymbol",
  cancel: "Cancel",
  color: "Color",
  mathtools: "Mathtools",
};
const PACKAGES = Object.keys(CONFIGURATIONS);
const { version: MATHJAX_VERSION } = JSON.parse(await readFile(join(packageRoot, "package.json"), "utf8"));

const entry = `
import { mathjax } from "mathjax-full/js/mathjax.js";
import { TeX } from "mathjax-full/js/input/tex.js";
import { SVG } from "mathjax-full/js/output/svg.js";
import { liteAdaptor } from "mathjax-full/js/adaptors/liteAdaptor.js";
import { RegisterHTMLHandler } from "mathjax-full/js/handlers/html.js";
${Object.entries(CONFIGURATIONS)
  .map(([name, file]) => `import "mathjax-full/js/input/tex/${name}/${file}Configuration.js";`)
  .join("\n")}

const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);

const document = mathjax.document("", {
  InputJax: new TeX({
    packages: ${JSON.stringify(PACKAGES)},
    formatError: (_jax, error) => {
      throw error;
    },
  }),
  OutputJax: new SVG({ fontCache: "none" }),
});

export function texToSvg(tex, isDisplay) {
  return adaptor.innerHTML(document.convert(tex, { display: isDisplay }));
}
`;

// The engine reads no file over 1 MiB, and the glyph paths of the fonts are over three quarters of that. A second entry
// that also imports the largest of them makes esbuild move them, with what they share with the first, into a chunk of
// their own. Nothing imports the second entry, so its own output is dropped.
const GLYPH_FONTS = ["normal", "bold", "italic", "monospace", "tex-mathit", "tex-oldstyle", "tex-variant"];
const VIRTUAL = {
  "virtual:math": entry,
  "virtual:glyphs": GLYPH_FONTS.map(
    (name, i) => `export * as font${i} from "mathjax-full/js/output/svg/fonts/tex/${name}.js";`,
  ).join("\n"),
};
const MAX_BYTES = 1024 * 1024;

const result = await build({
  entryPoints: { "math-svg": "virtual:math", "math-glyphs": "virtual:glyphs" },
  plugins: [
    {
      name: "virtual",
      setup(pluginBuild) {
        pluginBuild.onResolve({ filter: /^virtual:/ }, ({ path }) => ({ path, namespace: "virtual" }));
        pluginBuild.onLoad({ filter: /.*/, namespace: "virtual" }, ({ path }) => ({
          contents: VIRTUAL[path],
          resolveDir: root,
          loader: "js",
        }));
      },
    },
  ],
  outdir: outDir,
  chunkNames: "math-chunk-[hash]",
  splitting: true,
  bundle: true,
  format: "esm",
  platform: "neutral",
  mainFields: ["module", "main"],
  target: "es2023",
  define: { PACKAGE_VERSION: JSON.stringify(MATHJAX_VERSION) },
  minify: true,
  legalComments: "none",
  metafile: true,
  write: false,
});

// Every package in the bundle must carry a licence that may ship.
const packages = new Set(
  Object.keys(result.metafile.inputs).flatMap((input) => {
    const parts = input.split(/[\\/]/);
    const at = parts.lastIndexOf("node_modules");

    if (at === -1) {
      return [];
    }

    return [parts[at + 1]?.startsWith("@") ? `${parts[at + 1]}/${parts[at + 2]}` : parts[at + 1]];
  }),
);
const notices = [];

for (const name of [...packages].sort()) {
  const { license, version } = JSON.parse(await readFile(join(root, "node_modules", name, "package.json"), "utf8"));

  if (!ALLOWED_LICENSES.has(license)) {
    throw new Error(
      `${name}@${version} is licensed ${license}; only ${[...ALLOWED_LICENSES].join(", ")} may be bundled`,
    );
  }

  notices.push(`${name}@${version} (${license})`);
}

const licence = (await readFile(join(packageRoot, "LICENSE"), "utf8")).trim();
const header = [
  "// Generated by tools/build-math.mjs. Do not edit.",
  `// Bundles: ${notices.join(", ")}`,
  ...licence.split(/\r?\n/).map((line) => `// ${line}`.trimEnd()),
  "",
].join("\n");

await mkdir(outDir, { recursive: true });

for (const file of await readdir(outDir)) {
  if (file.startsWith("math-")) {
    await rm(join(outDir, file));
  }
}

const written = [];

for (const { path, text } of result.outputFiles) {
  if (basename(path) === "math-glyphs.js") {
    continue;
  }

  const bytes = Buffer.byteLength(header + text);

  if (bytes > MAX_BYTES) {
    throw new Error(`${basename(path)} is ${bytes} bytes; the engine reads no file over ${MAX_BYTES}`);
  }

  await writeFile(path, header + text);
  written.push(`${basename(path)} (${bytes} bytes)`);
}

await writeFile(
  join(outDir, "math-svg.d.ts"),
  "// Types for math-svg.js, written by tools/build-math.mjs.\n\nexport function texToSvg(tex: string, isDisplay: boolean): string;\n",
);

console.log(`wrote ${written.join(", ")} bundling ${notices.join(", ")}`);
