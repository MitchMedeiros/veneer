// Builds hooks/vendor/mermaid-ascii.js: the text renderer of beautiful-mermaid (MIT, lukilabs) bundled into one ES
// module the mod imports. The mod runs without Node, so it cannot import the package. Run after changing the version in
// package.json: `npm run build:mermaid`.

import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const packageRoot = join(root, "node_modules", "beautiful-mermaid");
const outDir = join(root, "hooks", "vendor");
const ALLOWED_LICENSES = new Set(["MIT"]);

const result = await build({
  stdin: {
    contents: "export { renderMermaidAscii } from './src/ascii/index.ts';",
    resolveDir: packageRoot,
    loader: "ts",
    sourcefile: "entry.ts",
  },
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2023",
  minify: true,
  legalComments: "none",
  metafile: true,
  write: false,
});

// Every package in the bundle must carry a licence that may ship.
const packages = new Set(
  Object.keys(result.metafile.inputs).flatMap((input) => {
    const parts = input.split(/[\\/]/);
    const at = parts.lastIndexOf("node_modules");

    if (at === -1) {
      return [];
    }

    return [parts[at + 1]?.startsWith("@") ? `${parts[at + 1]}/${parts[at + 2]}` : parts[at + 1]];
  }),
);
const notices = [];

for (const name of [...packages].sort()) {
  const { license, version } = JSON.parse(await readFile(join(root, "node_modules", name, "package.json"), "utf8"));

  if (!ALLOWED_LICENSES.has(license)) {
    throw new Error(
      `${name}@${version} is licensed ${license}; only ${[...ALLOWED_LICENSES].join(", ")} may be bundled`,
    );
  }

  notices.push(`${name}@${version} (${license})`);
}

const licence = (await readFile(join(packageRoot, "LICENSE"), "utf8")).trim();
const header = [
  "// Generated by tools/build-mermaid.mjs. Do not edit.",
  `// Bundles: ${notices.join(", ")}`,
  ...licence.split(/\r?\n/).map((line) => `// ${line}`.trimEnd()),
  "",
].join("\n");

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, "mermaid-ascii.js"), header + result.outputFiles[0].text);
await writeFile(
  join(outDir, "mermaid-ascii.d.ts"),
  "// Types for mermaid-ascii.js, written by tools/build-mermaid.mjs.\n\nexport function renderMermaidAscii(text: string, options?: { useAscii?: boolean }): string;\n",
);

console.log(`wrote hooks/vendor/mermaid-ascii.js (${notices.join(", ")})`);
